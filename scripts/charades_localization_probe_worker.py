#!/usr/bin/env python3
"""Frozen train-only localization probe: baseline, second look, evidence prompt.

No training or retrieval changes. Baseline verification is frozen. Revisions
run only after a parsed baseline match; invalid revisions fall back to baseline.
"""
from __future__ import annotations

import argparse
from datetime import datetime
import gc
import json
import math
import os
from pathlib import Path
import re
import time
from zoneinfo import ZoneInfo

from charades_timestamp_eval import load_official, source_payload, tensor_sha
from inspect_charades_localization_cases import ROOT, jsonl, save, sha

CHECKPOINT = ROOT / 'checkpoints/VideoSearchR1__charades-stage2'
ASSETS = ROOT / 'reports/47_charades_localization_probe_prepare.json'
PLAN = ROOT / 'reports/48_charades_localization_probe_cpu.json'
MAX_LENGTH, MAX_NEW = 20384, 1024
PROMPTS = {
    'ordinary': 'Review this same video again and independently determine the start and end of the event requested by the original query. A previous proposal was {start:.2f} to {end:.2f} seconds. Keep that proposal if it is accurate; otherwise correct it. Use the original query and visible video, and return the same required answer/start/end format.',
    'evidence': 'Review this same video again to verify the temporal evidence for the event requested by the original query. A previous proposal was {start:.2f} to {end:.2f} seconds. In <think>, cite displayed video timestamp labels and briefly describe the visible action at its beginning and end, checking the neighboring observations before and after it. Distinguish the actual requested action from preparation, merely holding its object, and subsequent activities. Determine an interval supported by those observations. Keep the proposal if supported; otherwise correct it. Do not infer an action merely from the scene or objects. Return the same required answer/start/end format.',
}


def system_prompt(module, arm, span=None):
    original = module._make_system_prompt('<REFINE>')
    if arm == 'baseline':
        return original
    if span is None:
        raise ValueError('Revisions require a baseline proposal, not GT')
    return original + '\n' + PROMPTS[arm].format(start=span[0], end=span[1])


def generation(module, processor, row, arm, span=None):
    # Only the query and pixels/metadata enter the model. Coarse text, GT and
    # split membership never enter prompts. Prior span is generated by baseline.
    result = module._build_generation_inputs(
        processor, system_prompt(module, arm, span), row['query'], row['pixel_path'],
        source_payload(row['metadata']), MAX_LENGTH, 16, 100352, 602112, 90316800)
    assert result['video_kwargs']['do_sample_frames'] is False
    meta = result['video_metadatas'][0]
    stamps = processor._calculate_timestamps(list(meta['frames_indices']), meta['fps'], 2)
    return result, [f'{t:.1f}' for t in stamps]


def check_cpu():
    if os.environ.get('CUDA_VISIBLE_DEVICES') != '':
        raise ValueError('CPU checks require CUDA hidden')
    import torch
    assets = json.loads(ASSETS.read_text())
    if assets['status'] != 'PIXELS_READY_PENDING_CPU_PROCESSOR_CHECK':
        raise ValueError('Fetch and validate selected train pixels first')
    if PLAN.exists():
        raise ValueError('Preserve existing CPU qualification')
    from run_charades_timestamp_full import verify
    verify(ROOT / 'reports/43_charades_timestamp_full_cpu.json')
    review = json.loads((Path(assets['output']) / 'text_quality_review.json').read_text())
    assert set(review['kept_indices']) == {r['index'] for r in assets['selection']}
    assert set(review['kept_indices']) <= set(review['reviewed_indices'])
    assert review['blocking_indices'] == []
    module = load_official('source')
    processor = module.AutoProcessor.from_pretrained(str(CHECKPOINT), local_files_only=True,
                                                     use_fast=True, padding_side='left')
    audits = []
    for row in assets['selection']:
        assert sha(row['pixel_path']) == row['pixel_sha256']
        reference = None
        for arm in ['baseline', 'ordinary', 'evidence']:
            inputs, labels = generation(module, processor, row, arm, None if arm == 'baseline' else [1.2, 3.4])
            batch = module._build_generation_batch_from_inputs(processor, inputs, MAX_LENGTH)
            tokens = int(batch['input_ids'].shape[1])
            # Leave room for changing the baseline proposal's digits at runtime.
            assert tokens < MAX_LENGTH - 64
            grid = batch['video_grid_thw'].tolist()
            pixels = tensor_sha(batch['pixel_values_videos'])
            signature = dict(pixel_sha256=pixels, video_grid=grid, time_labels=labels)
            if reference is None:
                reference = signature
            assert signature == reference
            decoded = processor.tokenizer.decode(batch['input_ids'][0], skip_special_tokens=False)
            assert re.findall(r'<([0-9.]+) seconds>', decoded) == labels
            audits.append(dict(index=row['index'], arm=arm, input_tokens=tokens,
                               visual_tokens=math.prod(grid[0]) // 4, **signature))
            del batch, inputs
        print(f'[CPU] {row["group"]}/{row["index"]}: pixel/grid/source-time equivalence passed', flush=True)
    assert not torch.cuda.is_initialized()
    groups = {g: {r['video_id'] for r in assets['selection'] if r['group'] == g} for g in ['dev', 'holdout']}
    assert not groups['dev'] & groups['holdout']
    # A small independent geometric check for scoring, not a model expectation.
    assert abs(module._compute_iou((2., 6.), (3., 7.)) - .6) < 1e-9
    files = [Path(__file__), ROOT / 'scripts/prepare_charades_localization_probe.py',
             ROOT / 'scripts/run_charades_localization_probe.py',
             ROOT / 'scripts/audit_charades_annotations.py',
             ROOT / 'scripts/charades_timestamp_eval.py', ASSETS,
             Path(assets['output']) / 'text_quality_review.json',
             CHECKPOINT / 'config.json', CHECKPOINT / '_vllm_compat/_compat_meta.json']
    plan = dict(status='CPU_QUALIFIED', output=assets['output'], assets_report=str(ASSETS),
                expected_records=len(assets['selection']), groups={g: len(v) for g, v in groups.items()},
                prompts=PROMPTS, max_input_tokens=MAX_LENGTH, max_new_tokens=MAX_NEW,
                conditions=['baseline', 'ordinary', 'evidence'],
                freeze='Original query, chosen top1 video, original verification decision, pixels, source timestamps and checkpoint. Only temporal post-processing differs.',
                budget='ordinary and evidence: at most one extra VLM call each, identical visual inputs, same 1024 generation cap; report actual text/output token costs separately.',
                fallback='If baseline is not matched or lacks a valid span: no revision. If revision is not matched, invalid or length-capped: keep baseline span. Verification/ranking never overwritten.',
                evaluation_scope=assets['evaluation_scope'], holdout_limit=assets['holdout_limit'],
                input_audits=audits, model_execution=False, cuda_initialized=False,
                file_sha256={str(p.relative_to(ROOT)): sha(p) for p in files})
    save(PLAN, plan)
    save(Path(assets['output']) / 'cpu_plan.json', plan)
    print(json.dumps({'status': plan['status'], 'plan': str(PLAN)}, ensure_ascii=False), flush=True)


def verify_plan():
    plan = json.loads(PLAN.read_text())
    assert plan['status'] == 'CPU_QUALIFIED'
    for relative, digest in plan['file_sha256'].items():
        assert sha(ROOT / relative) == digest, relative
    assert plan['prompts'] == PROMPTS
    return plan


def parse(module, text, duration, finish_reason):
    answer = module._parse_answer(text)
    span = module._parse_temporal_span(text, duration)
    return dict(answer=answer, span=list(span) if span is not None else None,
                usable=answer == 'matched' and span is not None and span[1] > span[0] and finish_reason != 'length',
                finish_reason=finish_reason)


def score(module, row, answer, span):
    return module._compute_iou(tuple(row['gt']), tuple(span)) if answer == 'matched' and span is not None else 0.


def run():
    plan = verify_plan()
    assets = json.loads(ASSETS.read_text())
    output = Path(plan['output'])
    predictions_path = output / 'paired_predictions.jsonl'
    if predictions_path.exists():
        raise ValueError('Preserve previous GPU attempt and select a fresh output for retry')
    module = load_official('source')
    import torch
    from vllm import LLM, SamplingParams
    assert str(torch.cuda.get_device_properties(0).uuid).removeprefix('GPU-') == os.environ['PROBE_GPU_UUID'].removeprefix('GPU-')
    processor = module.AutoProcessor.from_pretrained(str(CHECKPOINT), local_files_only=True,
                                                     use_fast=True, padding_side='left')
    compat = CHECKPOINT / '_vllm_compat'
    if not (compat / 'model.safetensors').is_file():
        raise ValueError('Require the previously verified official vLLM-compatible model')
    module._patch_vllm_qwen3_loader_for_soft_refine()
    started = time.monotonic()
    engine = LLM(model=str(compat), tensor_parallel_size=1, gpu_memory_utilization=.45,
                 max_num_seqs=1, max_model_len=MAX_LENGTH + MAX_NEW, dtype='bfloat16',
                 disable_custom_all_reduce=False, enforce_eager=True, seed=0)
    sampling = SamplingParams(n=1, temperature=0., top_p=1., top_k=-1,
                              max_tokens=MAX_NEW, repetition_penalty=1.)
    print('[GPU] engine ready; all prompts/configuration frozen before holdout inference', flush=True)
    with predictions_path.open('x') as handle, (output / 'generation_audit.jsonl').open('x') as audit:
        for position, row in enumerate(assets['selection']):
            assert sha(row['pixel_path']) == row['pixel_sha256']
            results, reference = {}, None
            arm_order = ['baseline'] + (['ordinary', 'evidence'] if position % 2 == 0 else ['evidence', 'ordinary'])
            for arm in arm_order:
                if arm != 'baseline' and not results['baseline']['usable']:
                    results[arm] = dict(executed=False, answer=results['baseline']['answer'],
                                        span=results['baseline']['span'], usable=False, fallback=True,
                                        input_tokens=0, output_tokens=0, elapsed_seconds=0.)
                    continue
                inputs, labels = generation(module, processor, row, arm,
                                             None if arm == 'baseline' else results['baseline']['span'])
                visual = dict(time_labels=labels, video_shapes=[list(x.shape) for x in inputs['video_inputs']],
                              pixel_tensor_sha256=[tensor_sha(x) for x in inputs['video_inputs']])
                if reference is None:
                    reference = visual
                assert reference == visual
                beginning = time.monotonic()
                generated = engine.generate([module._build_vllm_input_from_generation_inputs(inputs)],
                                            sampling_params=sampling, use_tqdm=False)[0]
                completion = generated.outputs[0]
                text = module._decode_completion_from_token_ids(processor.tokenizer, list(completion.token_ids))
                parsed = parse(module, text, row['annotation_duration'], completion.finish_reason)
                result = dict(**parsed, executed=True, raw_output=text,
                              input_tokens=len(generated.prompt_token_ids), output_tokens=len(completion.token_ids),
                              elapsed_seconds=round(time.monotonic() - beginning, 4), fallback=False)
                if arm != 'baseline' and not result['usable']:
                    result['span'] = results['baseline']['span']
                    result['fallback'] = True
                results[arm] = result
                audit.write(json.dumps(dict(index=row['index'], group=row['group'], arm=arm,
                                            prompt_sha256=__import__('hashlib').sha256(inputs['text'].encode()).hexdigest(),
                                            **visual), ensure_ascii=False) + '\n')
                audit.flush()
                del inputs
            baseline_answer = results['baseline']['answer']
            record = dict(index=row['index'], group=row['group'], video_id=row['video_id'],
                          query=row['query'], gt=row['gt'], initial_rank=row['initial_rank'],
                          frozen_verification=baseline_answer, arm_order=arm_order, conditions=results,
                          iou={arm: score(module, row, baseline_answer, results[arm]['span']) for arm in results})
            handle.write(json.dumps(record, ensure_ascii=False) + '\n'); handle.flush()
            save(output / 'progress.json', dict(status='running', completed=position + 1,
                 total=len(assets['selection']), current_group=row['group'], elapsed_seconds=time.monotonic() - started))
            print(f'[probe] {position + 1}/{len(assets["selection"])} {row["group"]}/{row["index"]} matched={baseline_answer} IoUs={record["iou"]}', flush=True)
            gc.collect()
    save(output / 'worker_complete.json', dict(status='complete', records=len(assets['selection']),
         elapsed_seconds=time.monotonic() - started, predictions_sha256=sha(predictions_path),
         plan_sha256=sha(PLAN), completed_at=datetime.now(ZoneInfo('Asia/Shanghai')).isoformat()))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cpu-check', action='store_true')
    parser.add_argument('--run', action='store_true')
    args = parser.parse_args()
    if args.cpu_check == args.run:
        parser.error('Choose exactly one action')
    check_cpu() if args.cpu_check else run()
